"""Development-only fit of public, action-specific block forecasts.

No previous calibration/holdout seeds are reused. The 3/4/5-player
mixed/shifted held-out seeds are NEVER generated by this script.
Run: python experiments/13_fit_action_calibration.py --games 1600
"""
from __future__ import annotations
import argparse
import csv
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'experiments'))
from action_calibration_common import (fit_offsets, fit_group, pg,
                                       predict, predict_rows, score,
                                       stages_for_games)

TRAIN_START = {'mixed': 1_350_000, 'shifted': 1_370_000}
SCREEN_START = {'mixed': 1_390_000, 'shifted': 1_410_000}
OUT = ROOT/'results'/'action_calibration'

def dump_csv(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        return
    with path.open('w',newline='',encoding='utf-8') as f:
        writer=csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader();writer.writerows(rows)


def run(games=1600, screen=500, boot=600):
    train_stages=[]
    for pop, start in TRAIN_START.items():
        _, samples=stages_for_games(4,pop,'opponent',(0.,)*4,start,games)
        train_stages.extend(samples)
        print('TRAIN',pop,'games',games,'stages',len(samples),flush=True)
    offsets=fit_offsets(train_stages, ridge=10.)
    counts=[sum(fit_group(s)==i for _,s in train_stages) for i in range(4)]
    fingerprint=hashlib.sha256(json.dumps(offsets).encode()).hexdigest()
    frozen={'status':'development_frozen', 'fit_version':1, 'fit_family':'blend25', 'fit_policy':'opponent',
            'seed_starts':TRAIN_START, 'training_games_per_population':games,
            'dev_screen_starts':SCREEN_START, 'dev_screen_games_per_population':screen,
            'ridge':10., 'groups':['steal_target_two','steal_target_one',
                                    'assassinate_target_two','assassinate_target_one'],
            'training_stage_counts':counts, 'offsets':offsets, 'sha256':fingerprint,
            'holdout_seed_policy':'3000000 + n_players*100000 + shifted*20000, 0..N-1; separate from all development seeds'}
    OUT.mkdir(parents=True,exist_ok=True)
    (OUT/'frozen_fit.json').write_text(json.dumps(frozen,indent=2)+'\n',encoding='utf-8')
    print('FROZEN offsets',offsets,'sha256',fingerprint,flush=True)
    results=[]
    for pop,start in SCREEN_START.items():
        for policy in ('opponent','opponent_action'):
            games_data,samples=stages_for_games(4,pop,policy,offsets,start,screen)
            stages=predict_rows(samples,offsets)
            scores=score(stages,games_data,screen,boot=boot,seed=start+123)
            for r in scores:
                r.update(population=pop,policy=policy,games=screen,seed_start=start)
            results.extend(scores)
            for action in ('steal','assassinate'):
                best=next(r for r in scores if r['action']==action and r['target']=='all'
                          and r['model']=='opponent_action')
                print('DEVELOPMENT SCREEN',pop,policy,action,
                      'n',best['stages'],'gap',round(best['gap'],3),
                      'Brier',round(best['brier'],3),flush=True)
    dump_csv(OUT/'development_screen.csv',results)
    return frozen,results


if __name__=='__main__':
    ap=argparse.ArgumentParser()
    ap.add_argument('--games',type=int,default=1600)
    ap.add_argument('--screen',type=int,default=500)
    ap.add_argument('--boot',type=int,default=600)
    args=ap.parse_args()
    run(args.games,args.screen,args.boot)
